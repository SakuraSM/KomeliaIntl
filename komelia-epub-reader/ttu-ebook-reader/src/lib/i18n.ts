let activeLocale = 'en';

export function setLocale(locale: string | undefined): void {
  activeLocale = locale?.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en';
  document.documentElement.lang = activeLocale;
}

export function t(message: string, values: MessageValues = {}): string {
  const translated = activeLocale === 'zh-CN' ? (zhCN[message] ?? message) : message;
  return Object.entries(values).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, String(value)),
    translated,
  );
}
